export function serviceLabel(
  key,
  language = "en"
) {
  const service =
    SERVICES.find(
      (item) =>
        item.key === key
    );

  if (!service) {
    return key;
  }

  return (
    service[language] ||
    service.en
  );
}

export function serviceIcon(
  key
) {
  const service =
    SERVICES.find(
      (item) =>
        item.key === key
    );

  return service?.icon || "🛠️";
}

